package ink.hoka.odyssey.client.api;

/**
 * Клиентский модуль Hoka Odyssey — то, что пишут разработчики (как {@code OdysseyModule} на сервере).
 * Jar модуля приходит с сервера, в нём {@code client-module.json}: {@code {"id": "...", "version": "...",
 * "main": "полное.имя.Класса"}}. Класс {@code main} — публичный, с конструктором без параметров.
 *
 * <p>Правила: всё регистрировать через {@link ClientContext} (тогда при выходе с сервера/перезагрузке модуля оно
 * снимется само); никаких mixin (их может только ядро — нужен новый крючок → просим ядро); логика игры — на сервере,
 * клиентский модуль только сообщает, что происходит, и рисует.
 */
public interface ClientModule {

    /** Модуль загружен (клиентский поток, игрок в мире). */
    void enable(ClientContext ctx);

    /** Модуль выгружается (выход с сервера, новая версия). Крючки снимет ядро; своё (потоки, файлы) — убрать здесь. */
    default void disable() {}
}
