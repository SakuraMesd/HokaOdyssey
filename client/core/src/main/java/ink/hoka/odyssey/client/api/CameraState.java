package ink.hoka.odyssey.client.api;

/**
 * Камера кадра — модуль может поменять любые поля в {@link ClientContext.CameraHook}. Углы — в градусах, как у
 * Minecraft: курс (yaw) — 0 юг, 90 запад; наклон (pitch) + — вниз; крен (roll) + — по часовой (правый борт вниз).
 * Крен — настоящий: видимость (отсечение) считается уже с ним.
 */
public final class CameraState {
    public double x, y, z;
    public float yaw, pitch, roll;
    /** Камера от 3-го лица (F5) — модуль может решить, что делать. */
    public boolean detached;
    /**
     * Полный поворот камеры (если задан модулем) — тогда yaw/pitch/roll для поворота не используются (только для
     * звука и прочего, что смотрит на углы игры). Без особых точек у «прямо вверх/вниз», крен на 360°, петли.
     */
    public org.joml.Quaternionf rotation;
    /**
     * 0.82 Поле зрения кадра (градусы по вертикали, как «Поле зрения» в настройках) — вместо того, что насчитала игра
     * (настройка игрока, бег, вода). 0 или меньше — как у игры. Рука от первого лица — как всегда.
     */
    public float fov;
}
